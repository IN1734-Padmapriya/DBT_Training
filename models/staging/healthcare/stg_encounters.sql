select 
TRIM(UPPER(ENCOUNTER_ID)) as ENCOUNTER_ID,
TRIM(UPPER(PATIENT_ID)) as PATIENT_ID,
TO_DATE(ADMIT_DATE) as ADMIT_DATE,
TO_DATE(DISCHARGE_DATE) as DISCHARGE_DATE,
TRIM(DIAGNOSIS_CODE) as DIAGNOSIS_CODE,
TRIM(STATUS) as STATUS,
CURRENT_TIMESTAMP() AS CREATED_AT
from {{ref('encounters')}}